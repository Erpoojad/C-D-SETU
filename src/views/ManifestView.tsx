import React, { useState } from 'react';
import { CheckCircle2, Printer, Search, XCircle } from 'lucide-react';
import { api } from '../api';
import { navigate } from '../lib/session';
import { dateTime, materialLabel, num } from '../lib/format';
import type { MaterialCategory } from '../types';
import { Button, Card, Input, Loading, PageHeader, useLoad } from '../components/ui';

interface Manifest {
  manifest_no: string;
  completed_at: string;
  generator: string;
  site_name: string;
  address: string;
  city: string;
  material: MaterialCategory;
  segregated: boolean;
  gross_t: number | null;
  tare_t: number | null;
  net_t: number;
  transporter: string;
  vehicle_registration: string | null;
  vehicle_category: string | null;
  facility: string;
  facility_address: string;
  ulb_authorization: string | null;
  co2_avoided_kg: number;
}

/** Public page: anyone holding a manifest number can verify it. */
export function ManifestView({ no }: { no?: string }) {
  const [input, setInput] = useState(no ?? '');
  return (
    <div className="max-w-3xl mx-auto px-4 sm:px-6 py-8">
      <div className="print:hidden">
        <PageHeader title="Verify a waste manifest" subtitle="Enter the manifest number printed on the movement document to confirm the load was delivered to a registered facility." />
        <form
          className="flex gap-2 mb-6"
          onSubmit={(e) => {
            e.preventDefault();
            if (input.trim()) navigate(`/manifest/${input.trim().toUpperCase()}`);
          }}
        >
          <Input value={input} onChange={(e) => setInput(e.target.value)} placeholder="CDS-2026-NAS-1A2B3C" />
          <Button type="submit"><Search className="w-4 h-4" /> Verify</Button>
        </form>
      </div>
      {no && <Lookup key={no} no={no} />}
    </div>
  );
}

function Lookup({ no }: { no: string }) {
  const m = useLoad(() => api.get<Manifest>(`/manifests/${encodeURIComponent(no)}`), [no]);
  if (m.loading) return <Loading />;
  if (m.error || !m.data)
    return (
      <Card className="p-6 flex items-start gap-3">
        <XCircle className="w-6 h-6 text-red-600 shrink-0" />
        <div>
          <div className="font-bold text-slate-900">Not verified</div>
          <div className="text-sm text-slate-600">No completed manifest numbered <b>{no}</b> exists on C&amp;D Setu.</div>
        </div>
      </Card>
    );
  const d = m.data;
  const row = (label: string, value: React.ReactNode) => (
    <div className="grid grid-cols-3 gap-3 py-2 border-b border-slate-100 text-sm">
      <dt className="text-slate-500">{label}</dt>
      <dd className="col-span-2 font-medium text-slate-900">{value}</dd>
    </div>
  );
  return (
    <Card className="p-6 sm:p-8 print:border-0 print:p-0">
      <div className="flex flex-wrap items-start justify-between gap-3 mb-4">
        <div>
          <div className="flex items-center gap-2 text-emerald-700 font-bold"><CheckCircle2 className="w-5 h-5" /> Verified delivery</div>
          <h2 className="text-xl font-extrabold text-slate-900 mt-1">C&amp;D Waste Movement Manifest</h2>
          <div className="text-sm text-slate-500">No. {d.manifest_no} · completed {dateTime(d.completed_at)}</div>
        </div>
        <Button variant="secondary" size="sm" className="print:hidden" onClick={() => window.print()}><Printer className="w-4 h-4" /> Print</Button>
      </div>
      <dl>
        {row('Generator', d.generator)}
        {row('Site', `${d.site_name}, ${d.address}, ${d.city}`)}
        {row('Material', `${materialLabel(d.material)} · ${d.segregated ? 'segregated at source' : 'mixed'}`)}
        {d.gross_t != null && d.tare_t != null && row('Weighbridge', `Gross ${num(d.gross_t, 2)} t − tare ${num(d.tare_t, 2)} t`)}
        {row('Net weight', <b>{num(d.net_t, 2)} t</b>)}
        {row('Transporter', `${d.transporter}${d.vehicle_registration ? ` · ${d.vehicle_category} ${d.vehicle_registration}` : ''}`)}
        {row('Delivered to', `${d.facility}, ${d.facility_address}`)}
        {row('Facility authorisation', d.ulb_authorization || 'Not stated by facility')}
        {row('CO₂ avoided (indicative)', `${num(d.co2_avoided_kg, 0)} kg`)}
      </dl>
      <p className="text-xs text-slate-500 mt-4">
        Record generated by C&amp;D Setu from data entered by the transporter at delivery. Verify at {window.location.origin}/#/manifest/{d.manifest_no}
      </p>
    </Card>
  );
}
